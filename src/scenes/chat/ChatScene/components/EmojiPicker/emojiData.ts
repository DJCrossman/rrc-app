const ALL_EMOJI = EMOJI_CATEGORIES.flatMap((category) => category.emojis);
const EMOJI_BY_CHAR = new Map(ALL_EMOJI.map((emoji) => [emoji.char, emoji]));

export function findEmoji(char: string): EmojiEntry {
	return EMOJI_BY_CHAR.get(char) ?? { char, name: char };
}

export function searchEmoji(query: string) {
	const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
	return ALL_EMOJI.filter((emoji) =>
		terms.every((term) => emoji.name.includes(term)),
	);
}
